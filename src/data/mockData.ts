// ─── Query Helper Functions ───────────────────────────────────────
export const getMetrics = (projs: Project[] = initialProjects, bgs: Bug[] = initialBugs, tsks: Task[] = initialTasks) => ({
  total:       projs.length,
  active:      projs.filter(p => p.status === 'Development').length,
  testing:     projs.filter(p => p.status === 'Testing').length,
  production:  projs.filter(p => p.status === 'Production').length,
  onHold:      projs.filter(p => p.status === 'On Hold').length,
  archived:    projs.filter(p => p.status === 'Archived').length,
  openBugs:    bgs.filter(b => b.status === 'Open' || b.status === 'In Progress').length,
  openTasks:   tsks.filter(t => t.status !== 'Done').length,
});

export const getProjectById = (id: string, projs: Project[] = initialProjects) => projs.find(p => p.id === id);
export const getTasksByProject = (pid: string, tsks: Task[] = initialTasks) => tsks.filter(t => t.projectId === pid);
export const getBugsByProject = (pid: string, bgs: Bug[] = initialBugs) => bgs.filter(b => b.projectId === pid);
export const getVersionsByProject = (pid: string, vers: Version[] = initialVersions) => vers.filter(v => v.projectId === pid);
export const getActivitiesByProject = (pid: string, acts: ActivityEvent[] = initialActivities) => acts.filter(a => a.projectId === pid);
export const getMemberById = (id: string, members: TeamMember[] = initialTeamMembers) => members.find(m => m.id === id);
export const getRecentProjects = (projs: Project[] = initialProjects) =>
  [...projs].sort((a, b) => new Date(b.lastUpdated).getTime() - new Date(a.lastUpdated).getTime()).slice(0, 5);

export const getNeedsAttention = (projs: Project[] = initialProjects, bgs: Bug[] = initialBugs, tsks: Task[] = initialTasks) => ({
  overdueTasks: tsks.filter(t => t.status !== 'Done' && new Date(t.dueDate) < new Date()),
  criticalBugs: bgs.filter(b => (b.status === 'Open' || b.status === 'In Progress') && (b.severity === 'High' || b.severity === 'Critical')),
  stalledProjects: projs.filter(p => {
    const lastUp = new Date(p.lastUpdated);
    const daysSince = (Date.now() - lastUp.getTime()) / (1000 * 60 * 60 * 24);
    return daysSince > 10 && p.status !== 'Archived' && p.status !== 'Production';
  }),
});
